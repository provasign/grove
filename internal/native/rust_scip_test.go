func TestRustScipParent(t *testing.T) {
	for symbol, want := range map[string]string{
		"rust-analyzer cargo ripgrep 15.1.0 util/impl#[TestCommand]assert_err().":         "TestCommand",
		"rust-analyzer cargo ripgrep 15.1.0 util/impl#[TestCommand][Display]fmt().":       "TestCommand",
		"rust-analyzer cargo ripgrep 15.1.0 util/TestCommand#cmd.":                        "TestCommand",
		"rust-analyzer cargo ripgrep 15.1.0 flags/lowargs/LoggingMode#Clear#name.":        "Clear",
		"rust-analyzer cargo ripgrep 15.1.0 regression/r16().":                            "",
		"rust-analyzer cargo ripgrep 15.1.0 hay/SHERLOCK.":                                "",
		"rust-analyzer cargo grep-printer 0.3.1 standard/StandardBuilder#build_json(+1).": "StandardBuilder",
	} {
		if got := rustScipParent(symbol); got != want {
			t.Errorf("rustScipParent(%q) = %q, want %q", symbol, got, want)
		}
	}
}

// scipTestIndex encodes a SCIP index with the fields decodeScip reads.
type scipTestDoc struct {
	path  string
	kinds map[string]int
	occs  []scipTestOcc
}

type scipTestOcc struct {
	rng, enclosing []int32
	symbol         string
	definition     bool
}

func scipTestIndex(docs ...scipTestDoc) []byte {
	packed := func(b []byte, num protowire.Number, ints []int32) []byte {
		var body []byte
		for _, v := range ints {
			body = protowire.AppendVarint(body, uint64(uint32(v)))
		}
		b = protowire.AppendTag(b, num, protowire.BytesType)
		return protowire.AppendBytes(b, body)
	}
	var index []byte
	for _, d := range docs {
		var doc []byte
		doc = protowire.AppendTag(doc, scipDocPath, protowire.BytesType)
		doc = protowire.AppendString(doc, d.path)
		for _, o := range d.occs {
			var occ []byte
			occ = packed(occ, scipOccRange, o.rng)
			occ = protowire.AppendTag(occ, scipOccSymbol, protowire.BytesType)
			occ = protowire.AppendString(occ, o.symbol)
			if o.definition {
				occ = protowire.AppendTag(occ, scipOccRoles, protowire.VarintType)
				occ = protowire.AppendVarint(occ, scipRoleDefinition)
			}
			if len(o.enclosing) > 0 {
				occ = packed(occ, scipOccEnclosingRange, o.enclosing)
			}
			doc = protowire.AppendTag(doc, scipDocOccurrences, protowire.BytesType)
			doc = protowire.AppendBytes(doc, occ)
		}
		for symbol, kind := range d.kinds {
			var info []byte
			info = protowire.AppendTag(info, scipInfoSymbol, protowire.BytesType)
			info = protowire.AppendString(info, symbol)
			info = protowire.AppendTag(info, scipInfoKind, protowire.VarintType)
			info = protowire.AppendVarint(info, uint64(kind))
			doc = protowire.AppendTag(doc, scipDocSymbols, protowire.BytesType)
			doc = protowire.AppendBytes(doc, info)
		}
		index = protowire.AppendTag(index, scipIndexDocuments, protowire.BytesType)
		index = protowire.AppendBytes(index, doc)
	}
	return index
}

// A test generated by a macro has no parsed symbol; rust-analyzer declares
// it (its span is the invocation) and its call into a parsed method lands.
func TestRustScipPassDeclaresMacroGeneratedItems(t *testing.T) {
	root := t.TempDir()
	write := func(rel, body string) {
		t.Helper()
		if err := os.MkdirAll(filepath.Dir(filepath.Join(root, rel)), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(root, rel), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("src/util.rs", `pub struct Tool;
impl Tool {
    pub fn run(&self) {}
}
`)
	write("tests/t.rs", `use crate::util::Tool;

// generated
check!(r16, |t: Tool| {
    t.run();
});

fn plain(t: Tool) {
    t.run();
}
`)
	const pkg = "rust-analyzer cargo demo 0.1.0 "
	raw := scipTestIndex(
		scipTestDoc{path: "src/util.rs", kinds: map[string]int{pkg + "util/Tool#": scipKindStruct, pkg + "util/impl#[Tool]run().": scipKindMethod}, occs: []scipTestOcc{
			{rng: []int32{0, 11, 15}, enclosing: []int32{0, 0, 0, 16}, symbol: pkg + "util/Tool#", definition: true},
			{rng: []int32{2, 11, 14}, enclosing: []int32{2, 4, 2, 24}, symbol: pkg + "util/impl#[Tool]run().", definition: true},
		}},
		scipTestDoc{path: "tests/t.rs", kinds: map[string]int{pkg + "t/r16().": scipKindFunction, pkg + "t/plain().": scipKindFunction}, occs: []scipTestOcc{
			{rng: []int32{3, 7, 10}, enclosing: []int32{2, 0, 5, 3}, symbol: pkg + "t/r16().", definition: true},
			{rng: []int32{3, 16, 20}, symbol: pkg + "util/Tool#"},
			{rng: []int32{4, 6, 9}, symbol: pkg + "util/impl#[Tool]run()."},
			{rng: []int32{7, 3, 8}, enclosing: []int32{7, 0, 9, 1}, symbol: pkg + "t/plain().", definition: true},
			{rng: []int32{8, 6, 9}, symbol: pkg + "util/impl#[Tool]run()."},
			{rng: []int32{8, 4, 5}, symbol: pkg + "t/r16()."},
			{rng: []int32{4, 4, 5}, symbol: "local 0"},
		}},
	)
	docs, err := decodeScip(raw)
	if err != nil {
		t.Fatal(err)
	}
	parsed := []core.SymbolRecord{
		{ID: "src/util.rs::Tool@a", FilePath: "src/util.rs", BlobSHA: "a", Language: "rust", Kind: core.KindStruct, Name: "Tool", QualifiedName: "Tool", Span: core.LineRange{Start: 1, End: 1}},
		{ID: "src/util.rs::Tool.run@a", FilePath: "src/util.rs", BlobSHA: "a", Language: "rust", Kind: core.KindMethod, Name: "run", QualifiedName: "Tool.run", ParentSymbol: "Tool", Span: core.LineRange{Start: 3, End: 3}},
		{ID: "tests/t.rs::crate@b", FilePath: "tests/t.rs", BlobSHA: "b", Language: "rust", Kind: core.KindModule, Name: "crate", QualifiedName: "crate", Span: core.LineRange{Start: 1, End: 11}},
		{ID: "tests/t.rs::plain@b", FilePath: "tests/t.rs", BlobSHA: "b", Language: "rust", Kind: core.KindFunction, Name: "plain", QualifiedName: "plain", Span: core.LineRange{Start: 8, End: 10}},
	}
	req := Request{Root: root, Files: []string{"src/util.rs", "tests/t.rs"}, Symbols: parsed}
	declared, edges := rustScipPass(req, docs)
	if len(declared) != 1 {
		t.Fatalf("want only r16 declared (plain and Tool.run are parsed), got %+v", declared)
	}
	r16 := declared[0]
	if r16.ID != "tests/t.rs::r16@b" || r16.Kind != core.KindFunction || r16.Span != (core.LineRange{Start: 3, End: 6}) || !slices.Contains(r16.Modifiers, "compiler-declared") {
		t.Fatalf("r16 record: %+v", r16)
	}
	want := map[string]bool{
		r16.ID + " calls src/util.rs::Tool.run@a":           true,
		r16.ID + " uses-type src/util.rs::Tool@a":           true,
		"tests/t.rs::plain@b calls " + r16.ID:               true,
		"tests/t.rs::plain@b calls src/util.rs::Tool.run@a": true,
	}
	for _, e := range edges {
		key := e.From + " " + string(e.Type) + " " + e.To
		if !want[key] {
			t.Errorf("unexpected edge %s", key)
		}
		delete(want, key)
	}
	for key := range want {
		t.Errorf("missing edge %s", key)
	}
}

