// The edges of a run survive an edit to their target's file: the endpoint is
// found again by name although its ID (blob SHA) and line changed, and an
// edge to a removed declaration drops.
func TestRustScipCacheFollowsEditedTargets(t *testing.T) {
	t.Setenv("XDG_CACHE_HOME", t.TempDir())
	t.Setenv("HOME", t.TempDir())
	root := t.TempDir()
	gen := core.SymbolRecord{ID: "tests/t.rs::r16@b", FilePath: "tests/t.rs", Language: "rust", Kind: core.KindFunction, Name: "r16", QualifiedName: "r16", Span: core.LineRange{Start: 3, End: 6}, Modifiers: []string{"compiler-declared"}}
	run := core.SymbolRecord{ID: "src/util.rs::Tool.run@a", FilePath: "src/util.rs", Language: "rust", Kind: core.KindMethod, Name: "run", QualifiedName: "Tool.run", Span: core.LineRange{Start: 3, End: 3}}
	stop := core.SymbolRecord{ID: "src/util.rs::Tool.stop@a", FilePath: "src/util.rs", Language: "rust", Kind: core.KindMethod, Name: "stop", QualifiedName: "Tool.stop", Span: core.LineRange{Start: 4, End: 4}}
	if err := saveRustScipCache(root, []core.SymbolRecord{gen, run, stop}, []core.Edge{
		symbolEdge(gen, run, core.EdgeCalls, 0.98), symbolEdge(gen, stop, core.EdgeCalls, 0.98),
	}); err != nil {
		t.Fatal(err)
	}
	edited := run
	edited.ID, edited.Span = "src/util.rs::Tool.run@c", core.LineRange{Start: 9, End: 9}
	record := readRustScipCache(root)
	if record == nil || !slices.Equal(record.Declared, []string{"tests/t.rs"}) {
		t.Fatalf("record: %+v", record)
	}
	edges := rustCachedEdges(record, []core.SymbolRecord{gen, edited})
	if len(edges) != 1 || edges[0].From != gen.ID || edges[0].To != edited.ID || edges[0].Type != core.EdgeCalls {
		t.Fatalf("want only r16 -> the edited Tool.run, got %+v", edges)
	}
	if readRustScipCache(t.TempDir()) != nil {
		t.Fatal("a repo with no record must report none")
	}
}

func TestRustItemMacroFiles(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{
		"a.rs": "rgtest!(r1, |d| {});\n",
		"b.rs": "macro_rules! m { () => {} }\n",
		"c.rs": "fn f() {\n    println!(\"x\");\n}\n",
		"d.rs": "// gen!(x);\nmod m {\n    bitflags::bitflags! {\n    }\n}\n",
	}
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(root, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	symbols := []core.SymbolRecord{{FilePath: "c.rs", Language: "rust", Kind: core.KindFunction, Span: core.LineRange{Start: 1, End: 3}}}
	got := rustItemMacroFiles(root, []string{"a.rs", "b.rs", "c.rs", "d.rs"}, symbols)
	if got["a.rs"] != "(" || got["d.rs"] != "{" || len(got) != 2 {
		t.Fatalf("item-level macro files = %v, want a.rs and d.rs (not a definition, a call in a body, or a comment)", got)
	}
}

// End to end against the real rust-analyzer, when it is installed.
func TestRustAnalyzerPassEndToEnd(t *testing.T) {
	bin, _ := rustAnalyzerBin()
	if bin == "" || !commandExists("cargo") {
		t.Skip("rust-analyzer or cargo not installed")
	}
	if out, err := exec.Command(bin, "--version").CombinedOutput(); err != nil {
		t.Skipf("rust-analyzer not runnable: %s", strings.TrimSpace(string(out)))
	}
	t.Setenv("GROVE_RUST_ANALYZER", bin)
	root := t.TempDir()
	write := func(rel, body string) {
		t.Helper()
		if err := os.MkdirAll(filepath.Dir(filepath.Join(root, rel)), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(root, rel), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("Cargo.toml", "[package]\nname = \"demo\"\nversion = \"0.1.0\"\nedition = \"2021\"\n")
	write("src/lib.rs", `pub struct Tool;
impl Tool {
    pub fn run(&self) {}
}
macro_rules! check {
    ($name:ident, $body:expr) => {
        pub fn $name() { $body(Tool) }
    };
}
check!(generated, |t: Tool| {
    t.run();
});
`)
	parsed := []core.SymbolRecord{
		{ID: "src/lib.rs::crate@a", FilePath: "src/lib.rs", BlobSHA: "a", Language: "rust", Kind: core.KindModule, Name: "crate", QualifiedName: "crate", Span: core.LineRange{Start: 1, End: 13}},
		{ID: "src/lib.rs::Tool@a", FilePath: "src/lib.rs", BlobSHA: "a", Language: "rust", Kind: core.KindStruct, Name: "Tool", QualifiedName: "Tool", Span: core.LineRange{Start: 1, End: 1}},
		{ID: "src/lib.rs::Tool.run@a", FilePath: "src/lib.rs", BlobSHA: "a", Language: "rust", Kind: core.KindMethod, Name: "run", QualifiedName: "Tool.run", ParentSymbol: "Tool", Span: core.LineRange{Start: 3, End: 3}},
		{ID: "src/lib.rs::check@a", FilePath: "src/lib.rs", BlobSHA: "a", Language: "rust", Kind: core.KindMacro, Name: "check", QualifiedName: "check", Span: core.LineRange{Start: 5, End: 9}},
	}
	res := (rustAnalyzer{}).Analyze(context.Background(), Request{Root: root, Files: []string{"src/lib.rs"}, Symbols: parsed})
	if len(res.Symbols) != 1 || res.Symbols[0].Name != "generated" || res.Symbols[0].Span.Start != 10 {
		t.Fatalf("want the macro-generated fn declared at its invocation, got %+v (diagnostics %v)", res.Symbols, res.Diagnostics)
	}
	for _, e := range res.Edges {
		if e.From == res.Symbols[0].ID && e.To == "src/lib.rs::Tool.run@a" && e.Type == core.EdgeCalls {
			return
		}
	}
	t.Fatalf("generated -> Tool.run did not land: %v (diagnostics %v)", res.Edges, res.Diagnostics)
}
